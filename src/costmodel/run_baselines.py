"""Fit every baseline on the training window and measure it on validation. The test window is not touched here."""

from __future__ import annotations

import json
import time

import pandas as pd

from costmodel import features as F
from costmodel.baselines import all_baselines
from costmodel.config import Config
from costmodel.evaluate import decile_table, summary
from costmodel.sources import load_table
from costmodel.split import assign


def run(cfg: Config) -> pd.DataFrame:
    """Also re-fits on each training window of ``cfg.exclude_year_sets`` (e.g. without the pandemic years)."""
    df = load_table(cfg)
    df["split"] = assign(df["admission_date"], cfg.split)
    df["period"] = df["admission_date"].dt.to_period("M").astype("string")
    valid = df[df["split"] == "valid"]
    train_all = df[df["split"] == "train"]
    train_windows = {"all training years": train_all}
    for years in cfg.exclude_year_sets:
        label = "without " + "-".join(map(str, years))
        train_windows[label] = train_all[~train_all["admission_date"].dt.year.isin(years)]

    X_valid = F.build_features(valid)
    rows, deciles = [], {}
    for window, train in train_windows.items():
        X_train = F.build_features(train)
        for model in all_baselines():
            t0 = time.perf_counter()
            model.fit(X_train, train[F.TARGET])
            pred = model.predict(X_valid)
            row = {"model": model.name, "train_window": window, "n_train": len(train), "n_valid": len(valid)}
            row |= summary(valid[F.TARGET].to_numpy(), pred, valid["period"])
            row["seconds"] = round(time.perf_counter() - t0, 1)
            if hasattr(model, "coverage_"):
                row["coverage"] = model.coverage_
            rows.append(row)
            deciles[(model.name, window)] = decile_table(valid[F.TARGET].to_numpy(), pred)
            print(
                f"{window:<20} {model.name:<26} MAE {row['mae']:9.2f}  monthly total err {row['monthly_total_mape']:5.2f}%"
            )

    results = pd.DataFrame(rows)
    cfg.reports_dir.mkdir(parents=True, exist_ok=True)
    (cfg.reports_dir / "baselines_valid.json").write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8", newline="\n")
    write_markdown(cfg, results, {m: t for (m, w), t in deciles.items() if w == "all training years"})
    return results


def write_markdown(cfg: Config, results: pd.DataFrame, deciles: dict[str, pd.DataFrame]) -> None:
    cols = ["model", "train_window", "mae", "rmse", "median_ae", "mae_top_decile", "bias_pct", "monthly_total_mape"]
    lines = [
        f"# Baselines on the validation window ({cfg.name})",
        "",
        f"Generated by `costmodel baselines --config {cfg.path.as_posix() if cfg.path else ''}`. Money in the dataset's"
        " currency. `bias_pct` = (sum predicted - sum paid) / sum paid. `monthly_total_mape` = mean absolute % error of"
        " each month's total cost. `mae_top_decile` = MAE on the 10% most expensive admissions.",
        "",
        results[cols].to_markdown(index=False, floatfmt=".2f"),
        "",
        "## Calibration by decile of actual cost (all training years)",
    ]
    for name, table in deciles.items():
        lines += ["", f"### {name}", "", table.to_markdown(floatfmt=".2f")]
    (cfg.reports_dir / "baselines_valid.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
