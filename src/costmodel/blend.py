"""``costmodel blend``: can two settings of the candidate be averaged to do well on both metrics?

The search (``costmodel train``) shows a trade-off: the setting with the lowest error per admission is usually not the
one with the lowest error on the month's total. This takes those two settings from the search, fits each on the
training window exactly as the search did, and measures weighted averages of their predictions on the validation
window: ``(1 - w) * per-admission model + w * month's-total model``.

Like ``costmodel families``, this is a comparison on the validation window only. It never reads the test window and
registers nothing. A blend that won here would have to be packaged as one model and go through the gate.
"""

from __future__ import annotations

import json

import mlflow
import pandas as pd

from costmodel import features as F
from costmodel import registry
from costmodel.candidate import CostModel
from costmodel.config import Config
from costmodel.evaluate import summary, to_markdown
from costmodel.train import choose, last_months, load_splits, setting_label

WEIGHTS = (0.0, 0.25, 0.5, 0.75, 1.0)  # share of the month's-total model in the average
KEEP = ("mae", "rmse", "mae_top_decile", "bias_pct", "monthly_total_mape")


def pair(search: pd.DataFrame, cfg: Config) -> tuple[pd.Series, pd.Series]:
    """The setting the search chose, and the one with the lowest error on the month's total."""
    return choose(search, cfg), search.sort_values(["monthly_total_mape", "mae"]).iloc[0]


def fit_setting(cfg: Config, row: pd.Series, train: pd.DataFrame, X_valid: pd.DataFrame, y_valid) -> CostModel:
    """One row of the search, fitted again the same way (same window, same early stopping, same seed)."""
    tc = cfg.train
    window = last_months(train, int(row["window_months"]))
    model = CostModel(
        row["objective"],
        int(row["num_leaves"]),
        tc.learning_rate,
        tc.max_rounds,
        tc.min_category_count,
        tc.seed,
        bool(row["use_time"]),
    )
    return model.fit(F.build_features(window), window[F.TARGET], X_valid, y_valid, tc.early_stopping_rounds)


def run(cfg: Config) -> pd.DataFrame:
    searched = cfg.reports_dir / "train_valid.json"
    if not searched.exists():
        raise RuntimeError(f"{searched} not found; run `costmodel train` first (the blend uses two of its settings)")
    search = pd.DataFrame(json.loads(searched.read_text(encoding="utf-8")))
    first, second = pair(search, cfg)
    same = first.name == second.name  # one setting is the best on both metrics: nothing to average

    df = load_splits(cfg)
    train, valid = df[df["split"] == "train"], df[df["split"] == "valid"]
    X_valid, y_valid = F.build_features(valid), valid[F.TARGET]
    registry.setup(cfg)
    rows = []
    with mlflow.start_run(run_name="blend"):
        mlflow.set_tags({"step": "blend", "dataset": cfg.name})
        mlflow.log_params({"per_admission": setting_label(first), "monthly_total": setting_label(second)})
        settings = (first,) if same else (first, second)
        preds = [fit_setting(cfg, row, train, X_valid, y_valid).predict(X_valid) for row in settings]
        for weight in (0.0,) if same else WEIGHTS:
            pred = preds[0] if same else (1 - weight) * preds[0] + weight * preds[1]
            metrics = summary(y_valid.to_numpy(), pred, valid["period"])
            rows.append({"weight": weight, **{k: metrics[k] for k in KEEP}})
            mlflow.log_metrics({f"valid_{k}_w{round(100 * weight)}": metrics[k] for k in ("mae", "monthly_total_mape")})
            print(f"share of the month's-total model {weight:4.0%}   MAE {metrics['mae']:9.2f}"
                  f"  monthly total err {metrics['monthly_total_mape']:5.2f}%")  # fmt: skip
    results = pd.DataFrame(rows)
    write_report(cfg, results, setting_label(first), setting_label(second))
    return results


def write_report(cfg: Config, results: pd.DataFrame, first: str, second: str) -> None:
    out = cfg.reports_dir
    out.mkdir(parents=True, exist_ok=True)
    best = choose(results, cfg)
    alone = results.iloc[0]
    payload = {
        "per_admission": first,
        "monthly_total": second,
        "best_weight": float(best["weight"]),
        "rows": json.loads(results.to_json(orient="records")),
    }
    (out / "blend_valid.json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8", newline="\n")
    ceiling = cfg.gate.max_monthly_total_mape
    lines = [
        f"# Blend of two candidate settings on the validation window ({cfg.name})",
        "",
        f"Generated by `costmodel blend --config {cfg.path.as_posix() if cfg.path else ''}`. Two settings from the search"
        " (`costmodel train`), fitted again the same way, and their predictions averaged:",
        "",
        f"- **Per-admission model** (the setting the search chose): {first}.",
        f"- **Month's-total model** (lowest error on the month's total in the search): {second}.",
        "",
    ]
    if len(results) == 1:
        lines += ["The same setting is the best on both metrics, so there is nothing to average.", ""]
    table = results.rename(columns={"weight": "share of the month's-total model"})
    lines += [
        to_markdown(table, index=False),
        "",
        "**Best by the search's own rule** (lowest MAE"
        + (f" among rows with monthly total error at most {ceiling:.0f}%" if ceiling is not None else "")
        + f"): {best['weight']:.0%} of the month's-total model."
        f" Against the chosen setting alone, MAE goes from {alone['mae']:.2f} to {best['mae']:.2f} and the monthly"
        f" total error from {alone['monthly_total_mape']:.2f}% to {best['monthly_total_mape']:.2f}%.",
        "",
        "Validation window only: the test window was not read and nothing was registered.",
    ]
    (out / "blend_valid.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
