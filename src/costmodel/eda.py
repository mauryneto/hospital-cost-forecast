"""Exploratory analysis: the few facts that shape the modelling decisions, written to ``reports/<dataset>/``."""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from costmodel.config import Config  # noqa: E402
from costmodel.sources import load_table  # noqa: E402
from costmodel.split import assign, windows  # noqa: E402

BLUE, ORANGE = "#2a78d6", "#eb6834"
INK, MUTED, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
WINDOW_SHADE = {"valid": "#f0efec", "test": "#e4e3df", "monitor": "#f0efec"}


def _style(ax: plt.Axes) -> None:
    ax.set_facecolor(SURFACE)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=MUTED, labelsize=9)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def variance_explained(log_y: pd.Series, groups: pd.Series) -> float:
    """Share of the variance of log(cost) explained by the group means (in-sample)."""
    group_mean = log_y.groupby(groups.values).transform("mean")
    return float(1 - ((log_y - group_mean) ** 2).sum() / ((log_y - log_y.mean()) ** 2).sum())


def monthly_chart(cfg: Config, df: pd.DataFrame, path) -> None:
    monthly = df.groupby(df["admission_date"].dt.to_period("M")).agg(n=("paid_amount", "size"), total=("paid_amount", "sum"))
    x = monthly.index.to_timestamp()
    spans = windows(df["admission_date"], cfg.split)
    fig, axes = plt.subplots(2, 1, figsize=(10, 5.5), sharex=True, facecolor=SURFACE)
    series = [
        (monthly["n"] / 1e3, "Admissions per month (thousands)", BLUE),
        (monthly["total"] / 1e6, "Total paid per month (millions)", ORANGE),
    ]
    for ax, (values, title, color) in zip(axes, series, strict=True):
        _style(ax)
        for name, (start, end) in spans.items():
            if name in WINDOW_SHADE:
                ax.axvspan(start, end, color=WINDOW_SHADE[name], zorder=0)
        ax.plot(x, values, color=color, linewidth=2)
        ax.set_title(title, loc="left", fontsize=11, color=INK)
        ax.set_ylim(bottom=0)
    for name, (start, end) in spans.items():
        axes[0].text(start + (end - start) / 2, axes[0].get_ylim()[1] * 0.05, name, ha="center", color=MUTED, fontsize=9)
    fig.suptitle(f"{cfg.name}: by admission month", x=0.01, ha="left", fontsize=12, color=INK)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def distribution_chart(df: pd.DataFrame, path) -> None:
    y = df["paid_amount"]
    fig, ax = plt.subplots(figsize=(10, 3.5), facecolor=SURFACE)
    _style(ax)
    ax.hist(y, bins=np.logspace(np.log10(y.min()), np.log10(y.max()), 80), color=BLUE, edgecolor=SURFACE, linewidth=0.5)
    ax.set_xscale("log")
    ax.set_title("Cost per admission (log scale)", loc="left", fontsize=11, color=INK)
    for q, label in [(0.5, "median"), (0.9, "p90"), (0.99, "p99")]:
        v = y.quantile(q)
        ax.axvline(v, color=MUTED, linewidth=0.8, linestyle="--")
        ax.text(v, ax.get_ylim()[1] * 0.92, f" {label} {v:,.0f}", color=MUTED, fontsize=9)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def run(cfg: Config) -> None:
    out = cfg.reports_dir
    out.mkdir(parents=True, exist_ok=True)
    df = load_table(cfg)
    df["split"] = assign(df["admission_date"], cfg.split)
    monthly_chart(cfg, df, out / "monthly_volume_and_cost.png")
    distribution_chart(df, out / "cost_distribution.png")

    train = df[df["split"] == "train"]
    log_y = np.log(train["paid_amount"])
    y = df["paid_amount"]
    top_decile_share = y[y >= y.quantile(0.9)].sum() / y.sum()
    by_year = df.groupby(df["admission_date"].dt.year).size()
    explained = {
        "requested procedure": variance_explained(log_y, train["requested_procedure"]),
        "main diagnosis": variance_explained(log_y, train["diagnosis_icd10"]),
        "hospital": variance_explained(log_y, train["provider_id"]),
        "admission type": variance_explained(log_y, train["admission_type"]),
    }
    lines = [
        f"# Exploratory analysis ({cfg.name})",
        "",
        f"Generated by `costmodel eda --config {cfg.path.as_posix() if cfg.path else ''}`.",
        "",
        f"- Admissions: **{len(df):,}**; by year: " + ", ".join(f"{year}: {n:,}" for year, n in by_year.items()),
        f"- Cost per admission: median {y.median():,.0f}, mean {y.mean():,.0f}, p99 {y.quantile(0.99):,.0f}.",
        f"- The 10% most expensive admissions account for **{100 * top_decile_share:.0f}%** of all money paid.",
    ]
    if "performed_procedure" in df:
        same = (df["requested_procedure"] == df["performed_procedure"]).mean()
        lines.append(f"- The requested procedure is the performed one in **{100 * same:.1f}%** of admissions.")
    lines += [
        "",
        "Share of the variance of log(cost) explained by each column alone (in-sample, training window):",
        "",
        "| Column | Variance explained |",
        "|---|---|",
        *[f"| {name} | {100 * v:.1f}% |" for name, v in explained.items()],
        "",
        "![Monthly volume and cost](monthly_volume_and_cost.png)",
        "",
        "![Cost distribution](cost_distribution.png)",
    ]
    (out / "eda.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))
